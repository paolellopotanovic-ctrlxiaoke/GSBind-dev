"""Build paired APEX manifests from existing Pinder/PeSTo monomer manifests.

The expected input is the manifest generated by the previous PeSTo-Pinder
pipeline. Each row describes one monomer case:

    system_id + input_state + side -> input_pdb_path + labels + label_mask

APEX needs a paired view:

    receptor structure + partner sequence -> receptor holo-derived labels

This script groups rows by system_id, pairs each receptor side with the opposite
side, extracts the partner sequence from the partner PDB, and writes a new CSV.
It does not download data; it only reuses existing PDB files from the prior
Pinder/PeSTo construction.
"""

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT_DIR / "src"))

from m4.data.structure_io import read_pdb


FIELD_SEP = ";"
AA3_TO_AA1 = {
    "ALA": "A",
    "ARG": "R",
    "ASN": "N",
    "ASP": "D",
    "CYS": "C",
    "GLN": "Q",
    "GLU": "E",
    "GLY": "G",
    "HIS": "H",
    "ILE": "I",
    "LEU": "L",
    "LYS": "K",
    "MET": "M",
    "PHE": "F",
    "PRO": "P",
    "SER": "S",
    "THR": "T",
    "TRP": "W",
    "TYR": "Y",
    "VAL": "V",
    "SEC": "U",
    "PYL": "O",
}


def read_csv(path):
    with open(path, "r", newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def write_csv(path, rows, fieldnames=None):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if fieldnames is None:
        fieldnames = []
        seen = set()
        for row in rows:
            for key in row:
                if key not in seen:
                    seen.add(key)
                    fieldnames.append(key)
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def split_field(text, cast=str):
    if text is None or text == "":
        return []
    return [cast(x) for x in str(text).split(FIELD_SEP)]


def sequence_from_pdb(pdb_path):
    structure = read_pdb(str(pdb_path))
    resids = structure["resid"]
    resnames = structure["resname"]
    het = structure.get("het_flag")
    chain = structure.get("chain_name")
    seen = set()
    seq = []
    for i, resid in enumerate(resids):
        if het is not None and str(het[i]) != "A":
            continue
        key = (str(chain[i]) if chain is not None else "", int(resid))
        if key in seen:
            continue
        seen.add(key)
        resname = str(resnames[i]).strip().upper()
        seq.append(AA3_TO_AA1.get(resname, "X"))
    return "".join(seq)


def usable(row, require_usable=True):
    if not require_usable:
        return True
    if str(row.get("low_mapping_quality", "0")) == "1":
        return False
    try:
        return int(float(row.get("num_positive_labels", 0))) > 0
    except ValueError:
        return False


def row_key(row):
    return (row.get("input_state", ""), row.get("side", ""))


def opposite_side(side):
    side = str(side).strip().upper()
    if side == "R":
        return "L"
    if side == "L":
        return "R"
    return ""


def build_rows(rows, states, require_usable_rows=True, partner_state="holo", max_residues=0):
    states = {x.strip() for x in states if x.strip()}
    grouped = defaultdict(dict)
    for row in rows:
        state = row.get("input_state", "")
        side = row.get("side", "")
        if state not in states and state != partner_state:
            continue
        if max_residues:
            try:
                if int(float(row.get("num_residues", 0))) > max_residues:
                    continue
            except ValueError:
                continue
        if not Path(row.get("input_pdb_path", "")).is_file():
            continue
        if state in states and not usable(row, require_usable=require_usable_rows):
            continue
        grouped[row["system_id"]][row_key(row)] = row

    output_rows = []
    errors = []
    sequence_cache = {}
    for system_id, by_case in sorted(grouped.items()):
        for state in sorted(states):
            for receptor_side in ["R", "L"]:
                receptor = by_case.get((state, receptor_side))
                if receptor is None:
                    continue
                partner_side = opposite_side(receptor_side)
                partner = by_case.get((partner_state, partner_side)) or by_case.get((state, partner_side))
                if partner is None:
                    errors.append(
                        {
                            "system_id": system_id,
                            "input_state": state,
                            "side": receptor_side,
                            "error": "missing_partner_row",
                        }
                    )
                    continue
                partner_path = partner.get("input_pdb_path", "")
                try:
                    if partner_path not in sequence_cache:
                        sequence_cache[partner_path] = sequence_from_pdb(partner_path)
                    partner_seq = sequence_cache[partner_path]
                except Exception as exc:
                    errors.append(
                        {
                            "system_id": system_id,
                            "input_state": state,
                            "side": receptor_side,
                            "partner_pdb_path": partner_path,
                            "error": repr(exc),
                        }
                    )
                    continue
                if not partner_seq:
                    errors.append(
                        {
                            "system_id": system_id,
                            "input_state": state,
                            "side": receptor_side,
                            "partner_pdb_path": partner_path,
                            "error": "empty_partner_sequence",
                        }
                    )
                    continue

                out = {
                    "apex_case_id": f"{receptor['case_id']}|partner:{partner_side}",
                    "receptor_case_id": receptor["case_id"],
                    "partner_case_id": partner["case_id"],
                    "system_id": system_id,
                    "pdb_id": receptor.get("pdb_id", ""),
                    "benchmark": receptor.get("benchmark", "pinder"),
                    "split": receptor.get("split", ""),
                    "cluster_id": receptor.get("cluster_id", ""),
                    "cluster_id_R": receptor.get("cluster_id_R", ""),
                    "cluster_id_L": receptor.get("cluster_id_L", ""),
                    "receptor_uniprot": receptor.get(f"uniprot_{receptor_side}", ""),
                    "partner_uniprot": receptor.get(f"uniprot_{partner_side}", ""),
                    "input_state": state,
                    "receptor_side": receptor_side,
                    "partner_side": partner_side,
                    "receptor_pdb_path": receptor.get("input_pdb_path", ""),
                    "partner_pdb_path": partner_path,
                    "partner_sequence": partner_seq,
                    "partner_length": len(partner_seq),
                    "labels": receptor.get("labels", ""),
                    "label_mask": receptor.get("label_mask", ""),
                    "input_residue_ids": receptor.get("input_residue_ids", ""),
                    "mapped_uniprot_positions": receptor.get("mapped_uniprot_positions", ""),
                    "num_residues": receptor.get("num_residues", ""),
                    "num_positive_labels": receptor.get("num_positive_labels", ""),
                    "mask_coverage": receptor.get("mask_coverage", ""),
                    "low_mapping_quality": receptor.get("low_mapping_quality", ""),
                    "apo_pair_system": receptor.get("apo_pair_system", "0"),
                    "source_receptor_manifest_row": receptor.get("case_id", ""),
                    "source_partner_manifest_row": partner.get("case_id", ""),
                    "label_source": "holo_heavy_atom_contact_5A_transferred_from_existing_manifest",
                }
                output_rows.append(out)
    return output_rows, errors


def summarize(rows, errors):
    counts = Counter()
    systems = set()
    for row in rows:
        counts[f"state:{row['input_state']}"] += 1
        counts[f"side:{row['receptor_side']}"] += 1
        systems.add(row["system_id"])
    return {
        "rows": len(rows),
        "systems": len(systems),
        "counts": dict(sorted(counts.items())),
        "errors": len(errors),
    }


def main():
    parser = argparse.ArgumentParser(description="Build APEX paired manifest from existing Pinder monomer manifest.")
    parser.add_argument("--input-manifest", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--states", default="apo,af2")
    parser.add_argument("--partner-state", default="holo", choices=["holo", "apo", "af2"])
    parser.add_argument("--max-residues", type=int, default=0)
    parser.add_argument("--allow-unusable", action="store_true")
    parser.add_argument("--limit-rows", type=int, default=0)
    args = parser.parse_args()

    input_rows = read_csv(args.input_manifest)
    if args.limit_rows:
        input_rows = input_rows[: args.limit_rows]
    rows, errors = build_rows(
        input_rows,
        states=args.states.split(","),
        require_usable_rows=not args.allow_unusable,
        partner_state=args.partner_state,
        max_residues=args.max_residues,
    )
    output_dir = Path(args.output_dir)
    write_csv(output_dir / "apex_paired_manifest.csv", rows)
    write_csv(output_dir / "apex_paired_manifest_errors.csv", errors)
    summary = summarize(rows, errors)
    summary["input_manifest"] = args.input_manifest
    summary["states"] = [x.strip() for x in args.states.split(",") if x.strip()]
    summary["partner_state"] = args.partner_state
    summary["max_residues"] = args.max_residues
    (output_dir / "apex_paired_manifest_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
